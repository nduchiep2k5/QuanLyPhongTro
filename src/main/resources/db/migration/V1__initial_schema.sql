-- Initial schema for an EMPTY demo/test database. No destructive statements.


create table accounts (
 id bigint generated by default as identity primary key,
 created_at timestamptz not null,
 updated_at timestamptz not null,
 version bigint not null default 0,
 email varchar(254) not null,
 password_hash varchar(255) not null,
 full_name varchar(120) not null,
 phone varchar(20),
 avatar_storage_key varchar(255),
 role varchar(30) not null,
 status varchar(30) not null
);

create table categories (
 id bigint generated by default as identity primary key,
 created_at timestamptz not null,
 updated_at timestamptz not null,
 version bigint not null default 0,
 name varchar(80) not null,
 active boolean not null
);

create table amenities (
 id bigint generated by default as identity primary key,
 created_at timestamptz not null,
 updated_at timestamptz not null,
 version bigint not null default 0,
 name varchar(80) not null,
 active boolean not null
);

create table rooms (
 id bigint generated by default as identity primary key,
 created_at timestamptz not null,
 updated_at timestamptz not null,
 version bigint not null default 0,
 landlord_id bigint not null references accounts(id) on delete restrict,
 category_id bigint not null references categories(id) on delete restrict,
 code varchar(40) not null,
 province varchar(100) not null,
 ward varchar(100) not null,
 address_line varchar(255) not null,
 latitude numeric(9,6),
 longitude numeric(9,6),
 area numeric(8,2) not null,
 max_occupants integer not null,
 status varchar(30) not null
);

create table listings (
 id bigint generated by default as identity primary key,
 created_at timestamptz not null,
 updated_at timestamptz not null,
 version bigint not null default 0,
 room_id bigint not null references rooms(id) on delete restrict unique,
 title varchar(180) not null,
 description text not null,
 monthly_rent numeric(14,2) not null,
 deposit numeric(14,2) not null,
 electricity_unit_price numeric(14,2) not null,
 water_unit_price numeric(14,2) not null,
 service_fee numeric(14,2) not null,
 water_billing_method varchar(30) not null,
 available_from date not null,
 moderation_status varchar(30) not null,
 visible boolean not null,
 submitted_at timestamptz,
 reviewed_at timestamptz,
 reviewed_by_id bigint references accounts(id) on delete restrict,
 moderation_reason varchar(1000)
);

create table room_images (
 id bigint generated by default as identity primary key,
 created_at timestamptz not null,
 updated_at timestamptz not null,
 version bigint not null default 0,
 room_id bigint not null references rooms(id) on delete restrict,
 storage_key varchar(255) not null unique,
 alt_text varchar(255),
 sort_order integer not null,
 is_cover boolean not null
);

create table room_amenities (
 id bigint generated by default as identity primary key,
 created_at timestamptz not null,
 updated_at timestamptz not null,
 version bigint not null default 0,
 room_id bigint not null references rooms(id) on delete restrict,
 amenity_id bigint not null references amenities(id) on delete restrict
);

create table favorites (
 id bigint generated by default as identity primary key,
 created_at timestamptz not null,
 updated_at timestamptz not null,
 version bigint not null default 0,
 account_id bigint not null references accounts(id) on delete restrict,
 room_id bigint not null references rooms(id) on delete restrict
);

create table rental_requests (
 id bigint generated by default as identity primary key,
 created_at timestamptz not null,
 updated_at timestamptz not null,
 version bigint not null default 0,
 listing_id bigint not null references listings(id) on delete restrict,
 tenant_id bigint not null references accounts(id) on delete restrict,
 status varchar(30) not null,
 requested_move_in date not null,
 message varchar(1000),
 listing_version_snapshot bigint not null,
 rent_snapshot numeric(14,2) not null,
 deposit_snapshot numeric(14,2) not null,
 title_snapshot varchar(180) not null,
 processed_at timestamptz,
 processed_by_id bigint references accounts(id) on delete restrict,
 decision_reason varchar(1000)
);

create table tenancies (
 id bigint generated by default as identity primary key,
 created_at timestamptz not null,
 updated_at timestamptz not null,
 version bigint not null default 0,
 request_id bigint not null references rental_requests(id) on delete restrict unique,
 room_id bigint not null references rooms(id) on delete restrict,
 tenant_id bigint not null references accounts(id) on delete restrict,
 status varchar(30) not null,
 planned_start_date date not null,
 actual_start_date date,
 end_date date,
 monthly_rent_snapshot numeric(14,2) not null,
 deposit_snapshot numeric(14,2) not null,
 room_address_snapshot varchar(500) not null,
 closure_reason varchar(1000)
);

create table reviews (
 id bigint generated by default as identity primary key,
 created_at timestamptz not null,
 updated_at timestamptz not null,
 version bigint not null default 0,
 tenancy_id bigint not null references tenancies(id) on delete restrict unique,
 rating integer not null,
 comment varchar(2000) not null,
 status varchar(30) not null
);

create table password_reset_tokens (
 id bigint generated by default as identity primary key,
 created_at timestamptz not null,
 updated_at timestamptz not null,
 version bigint not null default 0,
 account_id bigint not null references accounts(id) on delete restrict,
 token_hash varchar(64) not null unique,
 expires_at timestamptz not null,
 used_at timestamptz
);

create table moderation_events (
 id bigint generated by default as identity primary key,
 created_at timestamptz not null,
 updated_at timestamptz not null,
 version bigint not null default 0,
 actor_id bigint not null references accounts(id) on delete restrict,
 listing_id bigint references listings(id) on delete restrict,
 review_id bigint references reviews(id) on delete restrict,
 action varchar(30) not null,
 from_status varchar(30) not null,
 to_status varchar(30) not null,
 reason varchar(1000)
);

alter table accounts add constraint ck_accounts check (role in ('TENANT','LANDLORD','ADMIN') and status in ('ACTIVE','BANNED'));

alter table rooms add constraint ck_rooms check (area>0 and max_occupants>0 and status in ('AVAILABLE','RESERVED','OCCUPIED','MAINTENANCE','ARCHIVED') and ((latitude is null and longitude is null) or (latitude is not null and longitude is not null and latitude between -90 and 90 and longitude between -180 and 180)));

alter table listings add constraint ck_listings check (monthly_rent>0 and deposit>=0 and electricity_unit_price>=0 and water_unit_price>=0 and service_fee>=0 and water_billing_method in ('PER_M3','PER_PERSON') and moderation_status in ('DRAFT','PENDING_REVIEW','APPROVED','REJECTED','BLOCKED','ARCHIVED'));

alter table rental_requests add constraint ck_rental_requests check (status in ('PENDING','ACCEPTED','REJECTED','CANCELLED') and rent_snapshot>0 and deposit_snapshot>=0);

alter table tenancies add constraint ck_tenancies check (status in ('PENDING_MOVE_IN','ACTIVE','COMPLETED','CANCELLED') and monthly_rent_snapshot>0 and deposit_snapshot>=0 and (status not in ('ACTIVE','COMPLETED') or actual_start_date is not null) and (status<>'COMPLETED' or end_date is not null) and (status not in ('PENDING_MOVE_IN','CANCELLED') or actual_start_date is null) and (end_date is null or (actual_start_date is not null and end_date>=actual_start_date)));

alter table reviews add constraint ck_reviews check (rating between 1 and 5 and status in ('VISIBLE','HIDDEN','DELETED'));

alter table room_images add constraint ck_room_images check (sort_order>=0);

alter table moderation_events add constraint ck_moderation_events check ((listing_id is null) <> (review_id is null));

